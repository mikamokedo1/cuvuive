"""letter_paths.json -> src/libs/constants/letterPaths.ts"""
import json, sys
P = json.load(open(sys.argv[1]))
order = "a ă â b c d đ e ê g h i k l m n o ô ơ p q r s t u ư v x y".split()
lines = ['''// GENERATED by scripts/letter-paths (see README there). Do not edit by hand: rerun the scripts.
//
// Tracing templates for the Vietnamese lowercase alphabet, taken from the Playwrite VN font (the
// school-handwriting font used for lowercase letters elsewhere in the app), so what children trace
// matches what they read. Each letter is the font's centre line, zoomed to fill the 260x320 board
// together with its guide lines, so proportions follow the grade-1 grid: x-height 1 unit,
// ascenders 2.5, descenders 1.5. startPoint is where the pen goes down (grade-1 rules).

export interface LetterGuides {
  /** y of the top of b, h, k, l (2.5 units above the baseline) */
  ascender: number;
  /** y of the top of a, c, e, m, n, o... (1 unit above the baseline) */
  xLine: number;
  baseline: number;
  /** y of the bottom of g, p, q, y (1.5 units below the baseline) */
  descender: number;
}

export interface LetterPathData {
  path: string; // SVG path d attribute
  startPoint: { x: number; y: number }; // Starting point for the "start dot"
  viewBox: string; // SVG viewBox
  guides: LetterGuides;
}

export const LETTER_PATHS: Record<string, LetterPathData> = {''']
for l in order:
    d = P[l]; g = d["guides"]
    lines.append(f'''  "{l}": {{
    path: "{d["path"]}",
    startPoint: {{ x: {d["startPoint"]["x"]}, y: {d["startPoint"]["y"]} }},
    viewBox: "{d["viewBox"]}",
    guides: {{ ascender: {g["ascender"]}, xLine: {g["xLine"]}, baseline: {g["baseline"]}, descender: {g["descender"]} }},
  }},''')
lines.append("};\n")
open(sys.argv[2], "w", encoding="utf8").write("\n".join(lines))
print("written", sys.argv[2])
