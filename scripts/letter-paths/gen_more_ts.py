"""Rewrite the path tables in numberPaths.ts, numberPaths2.ts and tonePaths.ts from generated JSON,
keeping everything else in those files (types, NUMBER_NAMES_VI, getDigits)."""
import json, math, re, sys

D = json.load(open(sys.argv[1]))  # digit_paths.json
T = json.load(open(sys.argv[2]))  # tone_paths.json
root = sys.argv[3]  # frontend/src/libs/constants

HEADER = ("// GENERATED by scripts/letter-paths (see README there): do not edit the path table by hand.\n"
          "// Templates come from the Playwrite VN font (school handwriting), like the alphabet's.\n")


def length(strokes):
    return round(sum(math.dist(a, b) for s in strokes for a, b in zip(s, s[1:])))


def entry(key, d, guides=True):
    g = d.get("guides")
    gl = f'\n    guides: {{ top: {g["top"]}, baseline: {g["baseline"]} }},' if guides and g else ""
    return (f'  {key}: {{\n    path: "{d["path"]}",\n'
            f'    startPoint: {{ x: {d["startPoint"]["x"]}, y: {d["startPoint"]["y"]} }},\n'
            f'    viewBox: "{d["viewBox"]}",\n    estimatedLength: {length(d["strokes"])},{gl}\n  }},')


def replace_table(src, name, body):
    start = src.index(f"export const {name}")
    open_brace = src.index("{", src.index("=", start))
    depth, i = 0, open_brace
    while True:
        if src[i] == "{": depth += 1
        elif src[i] == "}":
            depth -= 1
            if depth == 0: break
        i += 1
    end = src.index(";", i) + 1
    decl = src[start:open_brace]
    return src[:start] + decl + "{\n" + body + "\n};" + src[end:]


def add_guides_type(src, iface):
    """Add an optional guides field to the interface, finding its closing brace by depth."""
    if "guides?:" in src:
        return src
    i = src.index("{", src.index(f"export interface {iface}"))
    depth = 0
    while True:
        if src[i] == "{": depth += 1
        elif src[i] == "}":
            depth -= 1
            if depth == 0: break
        i += 1
    field = "  /** y of the top and of the baseline of the digits (writing lines) */\n  guides?: { top: number; baseline: number };\n"
    return src[:i] + field + src[i:]


def strip_old_header(src):
    return re.sub(r"^// GENERATED by scripts/letter-paths.*?\n// Templates come from.*?\n", "", src, flags=re.S)


p = f"{root}/numberPaths.ts"
s = strip_old_header(open(p, encoding="utf8").read())
s = add_guides_type(s, "NumberPathData")
s = replace_table(s, "NUMBER_PATHS", "\n".join(entry(k, D[k]) for k in "123456789"))
open(p, "w", encoding="utf8").write(HEADER + s)

p = f"{root}/numberPaths2.ts"
s = strip_old_header(open(p, encoding="utf8").read())
s = add_guides_type(s, "DigitPathData")
s = replace_table(s, "DIGIT_PATHS", "\n".join(entry(k, D[k]) for k in "0123456789"))
open(p, "w", encoding="utf8").write(HEADER + s)

p = f"{root}/tonePaths.ts"
s = strip_old_header(open(p, encoding="utf8").read())
s = replace_table(s, "TONE_PATHS", "\n".join(entry(k, T[k], guides=False) for k in ["sac", "huyen", "hoi", "nga", "nang"]))
open(p, "w", encoding="utf8").write(HEADER + s)
print("written")
